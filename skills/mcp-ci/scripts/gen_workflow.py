#!/usr/bin/env python3
"""Write a GitHub Actions workflow that gates on the MCP review and probes the deployed endpoint.

Two jobs, both plain steps that run this plugin's scripts and gate on their
exit codes — no marketplace action, no model calls:

- **review** (every pull request and push): `lint_server.py --target <rev>`;
  the markdown goes to the job summary, the JSON to an artifact, and the exit
  code is the gate (1 fails the build). With `--alexa`, `validate_addon.py`
  runs too.
- **probe** (pushes to the default branch and manual runs, when the `MCP_URL`
  repository variable is set): `probe.py --legacy --budget-ms <ms>` against
  the deployed endpoint, with the token from the `MCP_TOKEN` secret. Exit 3
  (inconclusive: no or rejected token) becomes a warning annotation, said out
  loud rather than swallowed.

The plugin is fetched at a pinned tag (`--ref`, default `v<plugin version>`),
so the gate does not move under you.

Refuses to overwrite an existing workflow without `--force`. `--dry-run`
prints the file and writes nothing.

    gen_workflow.py <project> [--unit path] [--target 2026-07-28] [--budget-ms 500] [--alexa]
                    [--ref v0.2.0] [--out .github/workflows/mcp-conformance.yml] [--force]
                    [--dry-run] [--json]

Exit codes: 0 written (or printed), 1 the file exists and --force was not given, 2 usage.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # a read-only plugin install must stay clean: no __pycache__
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "lib"))

from mcp_server_skills import ALEXA_LATENCY_BUDGET_MS, REPOSITORY, SPEC_TARGET, __version__  # noqa: E402
from mcp_server_skills.cli import add_dry_run, fail, parser  # noqa: E402
from mcp_server_skills.inventory import build  # noqa: E402

TEMPLATE = """\
# Generated by the mcp-server plugin (gen_workflow.py). Edit freely; re-generate with --force.
name: MCP conformance

on:
  pull_request:
  push:
    branches: [{branch}]
  workflow_dispatch:

permissions:
  contents: read

env:
  MCP_SKILLS_REF: {ref}
  MCP_TARGET: "{target}"

jobs:
  review:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - name: Fetch the mcp-server plugin (pinned)
        run: git clone --depth 1 --branch "$MCP_SKILLS_REF" {repo} .mcp-skills
      - name: MCP review against ${{{{ env.MCP_TARGET }}}}
        run: |
          set +e
          python3 .mcp-skills/skills/mcp-review/scripts/lint_server.py "{unit}" --target "$MCP_TARGET" --json > mcp-review.json
          code=$?
          python3 .mcp-skills/skills/mcp-review/scripts/lint_server.py "{unit}" --target "$MCP_TARGET" >> "$GITHUB_STEP_SUMMARY"
          exit $code
{alexa_step}      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: mcp-review
          path: mcp-review.json

  probe:
    if: github.event_name != 'pull_request' && vars.MCP_URL != ''
    needs: review
    runs-on: ubuntu-latest
    steps:
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - name: Fetch the mcp-server plugin (pinned)
        run: git clone --depth 1 --branch "$MCP_SKILLS_REF" {repo} .mcp-skills
      - name: Probe ${{{{ vars.MCP_URL }}}} (both eras, {budget} ms budget)
        env:
          MCP_TOKEN: ${{{{ secrets.MCP_TOKEN }}}}
        run: |
          set +e
          args=(--legacy --n 20 --budget-ms {budget}{profile})
          if [ -n "$MCP_TOKEN" ]; then args+=(--token-env MCP_TOKEN); fi
          python3 .mcp-skills/skills/mcp-verify/scripts/probe.py "${{{{ vars.MCP_URL }}}}" "${{args[@]}}" --json > mcp-probe.json
          code=$?
          python3 -c "import json;d=json.load(open('mcp-probe.json'));print(json.dumps(d['discovered'].get('latency',{{}}),indent=2))" >> "$GITHUB_STEP_SUMMARY" || echo "no probe report" >> "$GITHUB_STEP_SUMMARY"
          if [ "$code" = 3 ]; then
            echo "::warning::MCP probe inconclusive (exit 3): the endpoint wants a token and MCP_TOKEN is missing or rejected"
            exit 0
          fi
          exit $code
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: mcp-probe
          path: mcp-probe.json
"""

ALEXA_STEP = """\
      - name: Alexa+ add-on manifest
        run: python3 .mcp-skills/skills/mcp-alexa/scripts/validate_addon.py "{addon}"
"""


def render(*, unit: str, target: str, budget: int, ref: str, alexa: bool, addon: str, branch: str) -> str:
    return TEMPLATE.format(
        unit=unit, target=target, budget=budget, ref=ref, repo=f"{REPOSITORY}.git", branch=branch,
        alexa_step=ALEXA_STEP.format(addon=addon) if alexa else "",
        profile=" --profile alexa" if alexa else "",
    )


def main(argv: list[str] | None = None) -> int:
    p = parser(__doc__)
    p.add_argument("project", nargs="?", default=".")
    p.add_argument("--unit", help="path of the server inside the repository (default: discovered)")
    p.add_argument("--target", default=SPEC_TARGET)
    p.add_argument("--budget-ms", type=int, default=ALEXA_LATENCY_BUDGET_MS)
    p.add_argument("--alexa", action="store_true", help="also validate addon.json and use the alexa probe profile")
    p.add_argument("--ref", default=f"v{__version__}", help="plugin tag to fetch (pin it)")
    p.add_argument("--branch", default="main")
    p.add_argument("--out", default=".github/workflows/mcp-conformance.yml")
    p.add_argument("--force", action="store_true", help="overwrite an existing workflow")
    p.add_argument("--json", action="store_true", help="print the write plan as JSON")
    add_dry_run(p)
    args = p.parse_args(argv)
    root = Path(args.project).expanduser().resolve()
    if not root.is_dir():
        return fail(f"{root} is not a directory")
    unit = args.unit
    addon = "addon.json"
    if unit is None:
        inventory = build(root)
        if not inventory.units:
            return fail(f"no MCP server under {root}; pass --unit")
        unit = str(inventory.units[0].path.relative_to(root)) or "."
        if inventory.layout.addon_files:
            addon = str(inventory.layout.addon_files[0].relative_to(root))
    content = render(unit=unit, target=args.target, budget=args.budget_ms, ref=args.ref, alexa=args.alexa,
                     addon=addon, branch=args.branch)
    out = root / args.out
    exists = out.is_file()
    plan = {"write": str(out), "exists": exists, "unit": unit, "target": args.target, "ref": args.ref,
            "secrets": ["MCP_TOKEN (optional)"], "variables": ["MCP_URL (enables the probe job)"]}
    if exists and not args.force and not args.dry_run:
        plan["written"] = False
        print(json.dumps(plan, indent=2) if args.json else f"{out} exists; pass --force to overwrite")
        return 1
    if args.dry_run:
        plan["written"] = False
        print(json.dumps({**plan, "content": content}, indent=2) if args.json else
              f"would write {out}:\n\n{content}")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    plan["written"] = True
    print(json.dumps(plan, indent=2) if args.json else f"wrote {out}\n"
          "next: set the MCP_URL repository variable (and the MCP_TOKEN secret if the endpoint needs one), "
          "then run lint_workflows.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
